import { AbstractControl, ValidationErrors } from '@angular/forms';

// Regex to validate international phone numbers with various formats.
// This regex attempts to cover a wide range of international phone number formats,
// including different placements of dashes, parentheses, and varying lengths.

// It will check if there is at least the + symbol at the beginning of the number provided.
const VALID_CHARACTERS: RegExp = /^\+/;
const VALIDATION_ERROR: { error: string } = { error: 'Invalid number phone.' };

export function internacionalPhoneNumberValidator(control: AbstractControl): ValidationErrors | null {
    return VALID_CHARACTERS.test(control.value) ? null : VALIDATION_ERROR;
}

export function internacionalValidPhone(phone: string) {
    return VALID_CHARACTERS.test(phone);
}

